fn check<D: Decoder>(
    mut decoder: D,
    mut input: &[u8],
    mut scratch: [D::Sample; 3],
    expected: &[i32],
    convert: impl Fn(D::Sample) -> I24,
) {
    decoder.finish();
    let mut values = Vec::new();
    let sentinel = I24::new_unchecked(12345);
    loop {
        let mut out = [sentinel; 5];
        let p =
            decode_as(&mut decoder, input, &mut scratch, &mut out, &convert).expect("valid FLAC");
        input = &input[p.consumed..];
        values.extend(out[..p.produced].iter().map(|x| x.inner()));
        assert!(out[p.produced..].iter().all(|x| *x == sentinel));
        if p.is_stalled() {
            break;
        }
    }
    assert!(input.is_empty());
    assert_eq!(values.len(), 35);
    assert!(values.iter().eq(expected.iter().cycle().take(35)));
}

#[test]
fn narrow_mono_to_wavegraph_q23() {
    check(
        Mono16::<16>::new(),
        PCM16,
        [0; 3],
        &[-8_388_608, -256, 0, 256, 8_388_352],
        I24::from_sample,
    );
}

#[test]
fn wide_mono_preserves_all_24_bits() {
    check(
        FlacDecoder::<i32, 16, 1>::new(),
        PCM24,
        [0; 3],
        &[-8_388_608, -1, 0, 1, 8_388_607],
        I24::from_sample,
    );
}

#[test]
fn output_requires_at_least_one_frame() {
    assert_eq!(
        decode_as(&mut Mono16::<16>::new(), PCM16, &mut [], &mut [0], |x| x),
        Err(Error::BufferTooSmall)
    );
}
